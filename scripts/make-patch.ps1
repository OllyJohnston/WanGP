<#
.SYNOPSIS
    Regenerate the WanGP Enhanced release assets.

.DESCRIPTION
    Produces two artefacts, both relative to the recorded upstream base commit
    (the first non-comment line of the UPSTREAM_BASE file at the repo root):

        dist/wangp-enhanced-v<version>-vs-<base>.patch          unified diff
        dist/wangp-enhanced-v<version>-vs-<base>-overlay.zip    changed files only

    The patch is generated by capturing git's stdout as raw bytes and writing
    them straight to disk. Both obvious shortcuts are wrong:

      * "git diff | Out-File" rewrites LF to CRLF, corrupting every hunk, and
      * letting PowerShell decode git's output mangles non-ASCII content
        (the README's emoji) because native output is decoded with the console
        code page - so the patch no longer matches the file it was made from.

    Raw bytes avoid both: git already emits patches with Unix line endings.

.PARAMETER Base
    Upstream commit to diff against. Defaults to the UPSTREAM_BASE file.

.PARAMETER OutDir
    Output directory. Defaults to "dist" (git-ignored).

.PARAMETER Repo
    Repository root. Defaults to the parent directory of this script.

.EXAMPLE
    scripts/make-patch.ps1
#>
[CmdletBinding()]
param(
    [string]$Base,
    [string]$OutDir = "dist",
    [string]$Repo
)

$ErrorActionPreference = "Stop"

# Capture native stdout as raw bytes, so no console code page can corrupt it.
function Invoke-GitBytes {
    param([string[]]$GitArgs)

    $startInfo = [System.Diagnostics.ProcessStartInfo]::new()
    $startInfo.FileName = "git"
    $startInfo.UseShellExecute = $false
    $startInfo.RedirectStandardOutput = $true
    $startInfo.RedirectStandardError = $true
    foreach ($argument in $GitArgs) { $startInfo.ArgumentList.Add($argument) }

    $process = [System.Diagnostics.Process]::Start($startInfo)
    $stderr = $process.StandardError.ReadToEndAsync()
    $buffer = New-Object System.IO.MemoryStream
    $process.StandardOutput.BaseStream.CopyTo($buffer)
    $process.WaitForExit()
    if ($process.ExitCode -ne 0) {
        throw "git $($GitArgs -join ' ') failed: $($stderr.Result)"
    }
    return $buffer.ToArray()
}

$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
if (-not $Repo) { $Repo = Split-Path -Parent $scriptDir }
$Repo = (Resolve-Path -LiteralPath $Repo).Path

if (-not $Base) {
    $baseFile = Join-Path $Repo "UPSTREAM_BASE"
    if (-not (Test-Path -LiteralPath $baseFile)) {
        throw "UPSTREAM_BASE not found at $baseFile and no -Base was supplied."
    }
    $Base = Get-Content -LiteralPath $baseFile |
        Where-Object { $_.Trim() -ne "" -and -not $_.Trim().StartsWith("#") } |
        Select-Object -First 1
    if ($Base) { $Base = $Base.Trim() }
}
if (-not $Base) { throw "Could not determine the upstream base commit." }

$wgpPath = Join-Path $Repo "wgp.py"
if (-not (Test-Path -LiteralPath $wgpPath)) { throw "wgp.py not found at $wgpPath." }
if ((Get-Content -LiteralPath $wgpPath -Raw) -notmatch 'WanGP_version\s*=\s*"([^"]+)"') {
    throw "Could not read WanGP_version from wgp.py."
}
$version = $Matches[1]

$shortBase = [System.Text.Encoding]::UTF8.GetString(
    (Invoke-GitBytes @("-C", $Repo, "rev-parse", "--short", $Base))
).Trim()
$stem = "wangp-enhanced-v$version-vs-$shortBase"

if (-not [System.IO.Path]::IsPathRooted($OutDir)) { $OutDir = Join-Path $Repo $OutDir }
New-Item -ItemType Directory -Force -Path $OutDir | Out-Null

# --- unified patch (byte-exact, LF) ------------------------------------------
$patchPath = Join-Path $OutDir "$stem.patch"
$patchBytes = Invoke-GitBytes @(
    "-C", $Repo, "--no-pager", "-c", "core.autocrlf=false",
    "diff", "--no-color", "--binary", $Base, "HEAD"
)
[System.IO.File]::WriteAllBytes($patchPath, $patchBytes)

# --- overlay zip (changed and added files, at their normal paths) ------------
$zipPath = Join-Path $OutDir "$stem-overlay.zip"
$nameBytes = Invoke-GitBytes @(
    "-C", $Repo, "--no-pager", "diff", "--name-only", "--diff-filter=ACMR", $Base, "HEAD"
)
$files = [System.Text.Encoding]::UTF8.GetString($nameBytes) -split "`n" |
    ForEach-Object { $_.Trim() } | Where-Object { $_ -ne "" }
if ($files.Count -eq 0) { throw "no changed files relative to $Base." }

$python = if (Get-Command python -ErrorAction SilentlyContinue) { "python" } else { "python3" }
$zipHelper = Join-Path $scriptDir "make_overlay_zip.py"
Push-Location $Repo
try {
    & $python $zipHelper $zipPath @files
    if ($LASTEXITCODE -ne 0) { throw "make_overlay_zip.py failed." }
}
finally { Pop-Location }

Write-Host "base:    $Base ($shortBase)"
Write-Host "files:   $($files.Count)"
Write-Host "patch:   $patchPath"
Write-Host "overlay: $zipPath"
